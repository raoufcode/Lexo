  const TABLES = { fr: FR, en: EN };
  let current = "fr";

  function setLang(code) {
    current = TABLES[code] ? code : "fr";
  }

  function t(key, ...args) {
    const table = TABLES[current] || FR;
    let s = table[key];
    if (s == null) s = FR[key];
    if (s == null) return key;
    args.forEach((a, i) => { s = s.split("$" + (i + 1)).join(String(a)); });
    return s;
  }

  /** Traduit les éléments [data-i18n] d'une page. */
  function apply(doc) {
    doc.documentElement.lang = current;
    doc.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.getAttribute("data-i18n")); });
    doc.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.getAttribute("data-i18n-title")); });
    doc.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.getAttribute("data-i18n-placeholder")); });
  }

  const LexoI18n = { t, setLang, apply, get lang() { return current; }, TABLES };
  root.LexoI18n = LexoI18n;
